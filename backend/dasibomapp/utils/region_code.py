# dasibomapp/utils/region_code.py


def get_region_code_by_location(lat: float, lng: float):
    """
    현재 좌표를 기준으로 사고다발지역 API에 필요한
    siDo, guGun 코드를 반환한다.

    임시 좌표 범위 방식.
    추후 역지오코딩 방식으로 변경 권장.
    """

    # --------------------------------------------------
    # 서울 마포구
    # 합정 / 홍대 / 망원 일대 포함
    # --------------------------------------------------
    if (
        37.52 <= lat <= 37.60
        and 126.88 <= lng <= 126.97
    ):
        return {
            "sido": "11",
            "gugun": "440",
            "region_name": "서울특별시 마포구",
        }

    # --------------------------------------------------
    # 서울 성동구
    # --------------------------------------------------
    if (
        37.52 <= lat <= 37.58
        and 127.00 <= lng <= 127.08
    ):
        return {
            "sido": "11",
            "gugun": "200",
            "region_name": "서울특별시 성동구",
        }

    # --------------------------------------------------
    # 경기도 광주시
    # --------------------------------------------------
    if (
        37.20 <= lat <= 37.60
        and 127.10 <= lng <= 127.50
    ):
        return {
            "sido": "41",
            "gugun": "610",
            "region_name": "경기도 광주시",
        }

    # --------------------------------------------------
    # 경기도 고양시 덕양구
    #
    # 기존 범위가 너무 넓어서 서울까지 포함됐음.
    # 일단 범위를 줄여둠.
    # --------------------------------------------------
    if (
        37.58 <= lat <= 37.75
        and 126.80 <= lng <= 127.00
    ):
        return {
            "sido": "41",
            "gugun": "281",
            "region_name": "경기도 고양시 덕양구",
        }

    return None